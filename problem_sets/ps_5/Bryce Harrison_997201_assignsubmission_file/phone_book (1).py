def search_by_first_name(first_name):
    results = []
    for phone, name_list in phone_book.items():
        if name_list[0].lower() == first_name.lower():
            results.append(phone)
    return results

def search_by_last_name(last_name):
    results = []
    for phone, name_list in phone_book.items():
        if name_list[1].lower() == last_name.lower():
            results.append(phone)
    return results

def search_by_full_name(first_name, last_name):
    results = []
    for phone, name_list in phone_book.items():
        if name_list[0].lower() == first_name.lower() and name_list[1].lower() == last_name.lower():
            results.append(phone)
    return results



