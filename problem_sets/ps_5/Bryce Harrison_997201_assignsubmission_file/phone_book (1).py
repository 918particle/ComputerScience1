def find_first(phone_book, first):
  matches = []
  for phone, name in phone_book.items():
    if name[0] == first:
      matches.append(phone)
  return matches

def find_last(phone_book, last):
  matches = []
  for phone, name in phone_book.items():
    if name[1] == last:
      matches.append(phone)
  return matches

def find_name(phone_book, first, last):
  matches = []
  for phone, name in phone_book.items():
    if name[0] == first and name[1] == last:
      matches.append(phone)
  return matches


print(find_first(phone_book, "Maria"))
