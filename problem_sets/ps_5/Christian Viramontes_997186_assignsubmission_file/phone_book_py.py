choice = input("Enter your choice: ").strip()

if choice == "1":
    first = input("First name: ").strip()
    matches = find_first(phone_book, first)
    if len(matches) == 0:
        print("No matching contacts found.")
    else:
        for phone in matches:
            print(phone)

elif choice == "2":
    last = input("Last name: ").strip()
